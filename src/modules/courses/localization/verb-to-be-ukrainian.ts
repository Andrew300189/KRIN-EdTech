// Keep this module compatible with the project's ES2020 production target.
// String.prototype.replaceAll requires ES2021 and made Vercel's type check
// fail before a deployment could be published.
function replaceEvery(value: string, source: string, target: string) {
  return value.split(source).join(target);
}

function translateLegacyLessonGoal(value: string) {
  const match = value.match(/^Цель урока:[\s\S]*?\n\nМаксимум за практику: (\d+) учебных очков\.[\s\S]*$/);
  if (!match) return value;

  // These cards were generated from a Russian-only legacy template. The
  // detailed target is already present in the lesson title and description;
  // this consistent Ukrainian goal keeps the reward card useful without
  // exposing a partially translated paragraph.
  return [
    "Мета уроку: послідовно виконайте завдання та застосуйте правило to be у коротких англійських фразах.",
    "",
    `Максимум за практику: ${match[1]} XP. Після першого завершення уроку винагорода нараховується за чинними правилами платформи; повторне проходження залишається доступним для тренування.`,
  ].join("\n");
}

function translateLegacyTheory(value: string) {
  const match = legacyTheoryReplacements.find(([needle]) => value.includes(needle));
  return match?.[1] ?? value;
}

/** Preserves English grammar examples while translating the surrounding learner copy. */
export function translateVerbToBeTextToUkrainian(value: string | null | undefined) {
  if (!value) return value;

  const theoryCopy = translateLegacyTheory(value);
  if (theoryCopy !== value) return theoryCopy;

  const goalCopy = translateLegacyLessonGoal(value);
  if (goalCopy !== value) return goalCopy;

  const exactCopy = exactReplacements.reduce(
    (translated, [source, target]) => replaceEvery(translated, source, target),
    value,
  );
  const curriculumCopy = curriculumReplacements.reduce(
    (translated, [source, target]) => replaceEvery(translated, source, target),
    exactCopy,
  );
  // Do not run the word-level fallback over authored Ukrainian copy. Some
  // Russian and Ukrainian stems overlap (for example, "говорим" and
  // "говоримо"), which otherwise corrupts a correctly translated phrase.
  if (curriculumCopy !== value) return curriculumCopy;

  return fallbackReplacements.reduce(
    (translated, [source, target]) => replaceEvery(translated, source, target),
    value,
  ).replace(/(^|\s)С (?=[A-Za-z])/g, "$1З ");
}

/** Recursively translates text stored inside an exercise JSON payload. */
export function translateVerbToBeJsonToUkrainian<T>(value: T): T {
  if (typeof value === "string") return translateVerbToBeTextToUkrainian(value) as T;
  if (Array.isArray(value)) return value.map((item) => translateVerbToBeJsonToUkrainian(item)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([key, item]) => [key, translateVerbToBeJsonToUkrainian(item)]),
    ) as T;
  }
  return value;
}
